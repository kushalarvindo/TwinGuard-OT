import React, { useEffect, useState } from 'react';
import { api } from '../api';
import type { Dataset } from '../types';
import { Download } from 'lucide-react';

function fmtBytes(bytes: number) {
  if (bytes === 0) return '0 B';
  const k = 1024, sizes = ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(2)) + ' ' + sizes[i];
}

function fmtDate(ts: number) {
  return new Date(ts * 1000).toLocaleString();
}

export default function DatasetsPage() {
  const [datasets, setDatasets] = useState<Dataset[]>([]);

  useEffect(() => {
    api.datasets.list().then(r => setDatasets(r as Dataset[])).catch(() => {});
  }, []);

  return (
    <div>
      <div className="page-header">
        <div className="page-title">Datasets</div>
        <div className="page-sub">Exportable CSV datasets generated by the simulation</div>
      </div>

      <div className="panel">
        <div className="panel-header">
          <span className="panel-title">Available Datasets</span>
          <span className="badge blue">{datasets.length} Files</span>
        </div>
        <div className="panel-body no-pad">
          {datasets.length === 0 ? (
            <div className="empty-state">No datasets found in data/results</div>
          ) : (
            <table className="data-table">
              <thead>
                <tr>
                  <th>Filename</th>
                  <th>Size</th>
                  <th>Created</th>
                  <th style={{ textAlign: 'right' }}>Action</th>
                </tr>
              </thead>
              <tbody>
                {datasets.map(d => (
                  <tr key={d.id}>
                    <td style={{ fontWeight: 500, color: 'var(--text-primary)' }}>{d.filename}</td>
                    <td className="mono">{fmtBytes(d.size_bytes)}</td>
                    <td className="mono" style={{ color: 'var(--text-muted)' }}>{fmtDate(d.created)}</td>
                    <td style={{ textAlign: 'right' }}>
                      <a
                        href={api.datasets.downloadUrl(d.id)}
                        className="btn btn-ghost"
                        style={{ padding: '4px 10px', fontSize: 11, textDecoration: 'none' }}
                        download
                      >
                        <Download size={12} />
                        Download
                      </a>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </div>
      </div>
    </div>
  );
}
